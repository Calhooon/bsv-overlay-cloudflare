fn main() {
    println!("-- NS2_RECORD_FIXTURE {}", record_fixture());
    let conn = Connection::open_in_memory().expect("open in-memory sqlite");
    for sql in OVERLAY_MIGRATIONS {
        if let Err(e) = conn.execute_batch(sql) {
            let msg = e.to_string().to_ascii_lowercase();
            assert!(
                msg.contains("duplicate column"),
                "production migration failed under real SQLite: {e}\n{sql}"
            );
        }
    }
    let mut out = String::from("-- bsv-low #499: the budget tier's fixture D1 (generated by `cargo run --example d1_budget_seed`)\n");
    let mut stmt = conn
        .prepare("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' ORDER BY rowid")
        .expect("schema read");
    let schema: Vec<String> = stmt
        .query_map([], |r| r.get::<_, String>(0))
        .expect("schema rows")
        .map(|r| r.expect("schema row"))
        .collect();
    for s in schema {
        out.push_str(&s);
        out.push_str(";\n");
    }

    let now_s = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .expect("clock")
        .as_secs();
    let mut rows: Vec<String> = Vec::new();
    let mut pot = |owner: char, identity: &str, i: u32| {
        let txid = pot_txid(owner, i);
        let opp = opponent(i + if owner == 'c' { 0 } else { 100_000 });
        let game = format!("{owner}0{i:062x}");
        rows.push(format!(
            "INSERT INTO pot_records (txid, outputIndex, spent, createdAt) VALUES ('{txid}', 0, 0, {now_s})"
        ));
        for (k, (me, them)) in [(identity, opp.as_str()), (opp.as_str(), identity)]
            .into_iter()
            .enumerate()
        {
            rows.push(format!(
                "INSERT INTO potparty_records (identity, opponentIdentity, gameId, potTxid, potVout, recoveryHeight, sigHex, txid, outputIndex, createdAt) \
                 VALUES ('{me}', '{them}', '{game}', '{txid}', 0, 958846, '3045ab', '{owner}{k}{i:062x}', 0, {now_s})"
            ));
        }
    };
    for i in 0..A_POTS {
        pot('a', ID_A, i);
    }
    for i in 0..B_POTS {
        pot('b', ID_B, i);
    }
    let noise: u32 = std::env::var("D1_BUDGET_NOISE")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(NOISE);
    for i in 0..noise {
        let stranger = format!("02{i:064x}");
        pot('c', &stranger, i);
    }
    // Exercise the hop-seat and valid-backup legs on A's unchanged eight outpoints.
    // Synthetic decoded columns and a latched seat marker, no transaction is broadcast.
    rows.push(format!("UPDATE pot_records SET lockKind='covenant', paramsDecoded=1, pubA='{ID_A}', pubB='{ID_B}', pubTower='{ID_A}', payPkhA='{}', payPkhB='{}', rakePkh='{}', stakeA=1, stakeB=1, feeSats=1, recoveryHeight=958846, potSats=2 WHERE txid LIKE 'aa%'", "11".repeat(20),"22".repeat(20),"33".repeat(20)));
    rows.push(format!("UPDATE potparty_records SET seatSettlePubkey='{ID_A}', seatSigHex='00', sigValid=1 WHERE identity='{ID_A}'"));
    rows.extend(d1_fleet::rows(now_s));
    let l23_start = rows.len();
    // executed whole (its bytes JSON holds commas): after `l23_start`
    rows.extend(identity_a_durable_spender_rows(now_s));
    rows.extend(l23_r2_route_rows(now_s));
    // NS-3 route pins: separate subjects, untouched by the budget scenarios.
    let parent = "f1".repeat(32);
    let seen = "f2".repeat(32);
    let mined = "f3".repeat(32);
    rows.push(format!("INSERT INTO pot_records (txid, outputIndex, spent, spendingTxid, spentConfirmed) VALUES ('{parent}',0,1,'{seen}',1)"));
    rows.push(format!("INSERT INTO hop_chain_probes (outpoint,probedAtMs,spent,spendingTxid,spentConfirmed) VALUES ('{parent}.0',1,1,'{seen}',1)"));
    for (id, word, tier, proof) in [
        (&seen, "seen", "hint", None),
        (
            &mined,
            "mined",
            "chain",
            Some(bsv_rs::transaction::MerklePath::from_coinbase_txid(&mined, 10).to_hex()),
        ),
    ] {
        let legacy = serde_json::json!({"txid":id,"present":true,"confirmed":true,"height":null,"rawHex":null,"source":"external","unconfirmable":false,"claimedHeight":10}).to_string();
        let (height, root, hex, hash) = match proof {
            Some(hex) => (
                "10".to_string(),
                format!("'{id}'"),
                format!("'{hex}'"),
                format!("'{}'", "f4".repeat(32)),
            ),
            None => ("NULL".into(), "NULL".into(), "NULL".into(), "NULL".into()),
        };
        rows.push(format!("INSERT INTO tx_words (txid,word,tier,height,proof_root,proof_height,proof_hex,header_hash,hint_source,hint_at,updated_at,legacy_body) VALUES ('{id}','{word}','{tier}',{height},{root},{height},{hex},{hash},'woc',123,123,'{legacy}')"));
    }
    rows.extend(e649_hook_rows(now_s));
    rows.extend(fix837_c_rows(now_s));
    for (i, r) in rows.iter().enumerate() {
        if r.starts_with("UPDATE ") || i >= l23_start {
            conn.execute_batch(r).unwrap();
        } else {
            d1_fleet::execute_row(&conn, r);
        }

        out.push_str(r);
        out.push_str(";\n");
    }
    // bsv-low #645: the schema dump carries the count's triggers, not its row: the backfill the overlay's migration
    // runs, run here after the rows (a no-op on the native connection, which already holds it).
    // NS-COST-BAR-1: the same for each trigger-kept count (its set fills from the rows' triggers on the local D1,
    // its count row from the backfill).
    for backfill in bsv_overlay_cloudflare::ops::COUNT_ROW_BACKFILLS {
        conn.execute_batch(backfill).unwrap();
        out.push_str(backfill);
        out.push_str(";\n");
    }
    if let Ok(path) = std::env::var("D1_CURSOR_PIN_SQL") {
        cursor_measure::write(&conn, &path, now_s, d1_fleet::WHALE);
    }
    print!("{out}");
}

/// bsv-low #693 fold-2 / #723: identity A's one swept hop whose sweep is a DURABLE spender (its bytes in the
/// spender store) with a `proofmined:` latch past the #484 grace, so A's owed recompute makes the latch range read
/// (`owed-first-read`) and serves the row from the latch. A synthetic hop and sweep: no transaction is broadcast.
fn identity_a_durable_spender_rows(now_s: u64) -> Vec<String> {
    let hop = "a7".repeat(32);
    let sweep = "a8".repeat(32);
    // A's first game (pot `aa..0`, seat A, payPkhA `11..`): the sweep pays A's committed home
    let game = format!("a0{:062x}", 0);
    let bytes = low_app_layer::owed::StoredSpenderBytes {
        inputs: vec![(hop.clone(), 0)],
        outputs: vec![low_app_layer::owed::StoredSpenderOutput {
            vout: 0,
            pkh: Some("11".repeat(20)),
            sats: 19_800,
            pot: false,
        }],
    }
    .to_json_capped()
    .expect("under the cap");
    let latched_at_ms = now_s * 1000 - 40 * 60_000;
    vec![
        format!("INSERT INTO hopparty_records (identity, opponentIdentity, gameId, hopVout, hopSats, seatSettlePubkey, seatSigHex, identitySigHex, hopLockHex, hopSatsOnChain, containerOutputs, markerValid, txid, outputIndex, createdAt) VALUES ('{ID_A}', '{ID_B}', '{game}', 0, 20000, '{ID_A}', '00', '00', 'aa', 20000, 3, 1, '{hop}', 2, {now_s})"),
        format!("INSERT INTO pot_records (txid, outputIndex, spent, spendingTxid, spentConfirmed, createdAt) VALUES ('{hop}', 0, 1, '{sweep}', 0, {now_s})"),
        format!("INSERT INTO owed_spender_bytes (txid, bytesJson, createdAtMs) VALUES ('{sweep}', '{bytes}', {})", now_s * 1000),
        format!("INSERT INTO hop_chain_probes (outpoint, probedAtMs, spent, spendingTxid, spentConfirmed) VALUES ('{}{sweep}.900000', {latched_at_ms}, 1, '{}', 1)", low_app_layer::owed::PROOF_MINED_LATCH_PREFIX, "ab".repeat(32)),
    ]
}

