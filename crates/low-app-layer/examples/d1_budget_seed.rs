//! bsv-low #499: the fixture D1 of the budget tier (`make ci-d1-budget`, `tools/lane-499`).
//!
//! Prints one SQL script to stdout: the overlay's PRODUCTION schema (the migration list applied to real SQLite
//! exactly as the overlay's runner does, then dumped from `sqlite_master`, so the script carries no re-run ALTER
//! that `wrangler d1 execute` would refuse) and the fixture rows, every row first executed against that schema
//! here (a row the schema refuses fails this program, never the tier). The tier loads it with
//! `wrangler d1 execute low-overlay-db --local --persist-to <dir> --file <script>` and serves the app layer over it.
//!
//! A and B retain the original eight-pot and two-pot budget scenarios. Fleet noise includes 22k pot/hop
//! outpoints, 7,549 hop markers, 14k parties, 7,209 backups and sweeps, 19,005 proven transactions and
//! 150 evictions. A separate whale has 1,033 party rows and 554 hops, including hop-only pot candidates.
//! The shared fleet fixture also drives the native plan and compatibility pins. Noise never shares A or B's
//! keys, so their route ceilings still measure the cost of a fixed request as the fleet grows.

use bsv_overlay_cloudflare::d1::OVERLAY_MIGRATIONS;
use rusqlite::Connection;

const A_POTS: u32 = 8;
const B_POTS: u32 = 2;
/// The strangers (`D1_BUDGET_NOISE` overrides it, to see which route's rows grow with the user count).
const NOISE: u32 = 300;

/// Identity A (the scenarios') and B (the shed leg's), lowercase compressed keys.
const ID_A: &str = "02a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1a1";
const ID_B: &str = "02b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2b2";

fn pot_txid(owner: char, i: u32) -> String {
    format!("{owner}{owner}{i:062x}")
}

fn opponent(i: u32) -> String {
    format!("03{i:064x}")
}

